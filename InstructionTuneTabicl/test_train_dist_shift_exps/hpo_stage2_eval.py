#!/usr/bin/env python
"""
hpo_stage2_eval.py
==================
Post-hoc Stage-2 evaluation of the best checkpoint saved for every HPO setting.

Overview
--------
During the HPO sweep (``train_gp_hpo.py`` / ``GPTrainer``),
**Stage-1 evaluation** is run after every training step using the first
``n_eval`` rows of ``eval_manifest.csv``.  The best checkpoint (highest
Stage-1 eval accuracy) is saved as ``best-eval-step-<N>.ckpt`` inside each
run's checkpoint directory.

**Stage-2 evaluation** (this script) runs *once* per HPO setting, on a fresh
held-out slice of the eval manifest that was **not** used during training:

  eval_manifest row indices used
  ──────────────────────────────
  Stage-1  :  0  …  n_eval − 1                (used every training step)
  Stage-2  :  n_eval  …  n_eval + n_stage2 − 1
             where  n_stage2 = floor( (total_rows − n_eval) / 2 )

The second half of the remaining rows is deliberately reserved for any future
Stage-3 evaluation.

Results are appended as three new columns to the HPO manifest CSV and the
file is re-saved in place:

  ``stage2_eval_acc``
      Mean accuracy across all Stage-2 eval tasks for the best checkpoint.
  ``stage2_eval_ce``
      Mean cross-entropy loss across all Stage-2 eval tasks.
  ``stage2_last_row_used``
      0-based index of the last eval-manifest row consumed by either Stage-1
      or Stage-2 evaluation.  Identical for every run in an HPO sweep.

Usage
-----
::

    python hpo_stage2_eval.py --manifest_path /lustre/isaac24/scratch/adas23/PostR01SubmissionFeb2026/test_train_dist_shift/logs/hpo_runs/20260304_014354/hpo_runs_manifest.csv --n_eval 10 --data_dir /lustre/isaac24/scratch/adas23/PostR01SubmissionFeb2026/test_train_dist_shift/data

Optional:
  --device          cuda | cpu  (default: cuda if available)
  --max_features    int         (default: auto-compute from eval manifest)
  --eval_seed       int         (default: 0  – kept separate from stage-1 seed)
  --force_reeval    re-evaluate even if stage2 columns already exist

This script can be run on **old HPO manifests** generated by earlier sweeps as
long as the checkpoint and data directories are still accessible.
"""

