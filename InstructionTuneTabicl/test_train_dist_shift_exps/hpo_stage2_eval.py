# Stage-2 eval-batch preparation
# ---------------------------------------------------------------------------

def prepare_stage2_eval_batch(
    data_dir: str,
    n_eval_stage1: int,
    eval_manifest_filename: str = "eval_manifest.csv",
    max_features: Optional[int] = None,
    seed: int = 1,
) -> Tuple[List, int, int]:
    """
    Build the Stage-2 evaluation task list from the held-out eval manifest slice.

    Stage-2 uses the **first half** of eval-manifest rows that were not
    consumed by Stage-1.  The second half is reserved for any future use.

    Parameters
    ----------
    data_dir : str
        Root directory containing ``eval_manifest_filename`` and pickle files.
    n_eval_stage1 : int
        Number of rows from the top of the manifest that Stage-1 already used.
        Stage-2 starts at row index ``n_eval_stage1``.
    eval_manifest_filename : str
        Filename of the eval manifest CSV inside ``data_dir``.
    max_features : int | None
        Must match the value used during training.  If None, auto-computed
        from the Stage-2 manifest slice using ``max(A + N)``.
    seed : int
        RNG seed for the ``_build_task`` sampling (kept distinct from Stage-1
        seed to ensure independent samples).

    Returns
    -------
    tasks : list
        List of ``(X_i, y_i, n_feat, seq_len, train_size)`` tuples.
    n_stage2 : int
        Number of eval tasks in the Stage-2 batch.
    last_row_used : int
        0-based index of the last eval-manifest row consumed across both
        Stage-1 and Stage-2 (= ``n_eval_stage1 + n_stage2 - 1``).

    Raises
    ------
    ValueError
        If there are not enough remaining rows to form a Stage-2 batch.
    """
    from gp_dataset import _build_task

    data_dir = Path(data_dir)
    manifest = pd.read_csv(data_dir / eval_manifest_filename)
    total_rows = len(manifest)

    if total_rows <= n_eval_stage1:
        raise ValueError(
            f"eval_manifest has only {total_rows} rows, but Stage-1 already "
            f"uses {n_eval_stage1}.  No rows remain for Stage-2 evaluation."
        )

    remaining_rows = total_rows - n_eval_stage1
    n_stage2 = remaining_rows // 2              # first half of what's left

    if n_stage2 == 0:
        raise ValueError(
            f"Only {remaining_rows} row(s) remain after Stage-1 "
            f"(n_eval={n_eval_stage1}).  Need at least 2 remaining rows for "
            f"a non-empty Stage-2 batch."
        )

    stage2_slice = manifest.iloc[n_eval_stage1 : n_eval_stage1 + n_stage2]

    if max_features is None:
        max_features = int((stage2_slice["A"] + stage2_slice["N"]).max())

    rng = np.random.default_rng(seed)
    pkl_cache: Dict[str, dict] = {}
    tasks = []

    for _, row in stage2_slice.iterrows():
        X_i, y_i, n_feat, seq_len, train_sz = _build_task(
            train_pkl_path=str(row["path_to_train"]),
            test_pkl_path=str(row["path_to_test"]),
            max_features=max_features,
            rng=rng,
            pkl_cache=pkl_cache,
        )
        tasks.append((X_i, y_i, n_feat, seq_len, train_sz))

    last_row_used = n_eval_stage1 + n_stage2 - 1
    return tasks, n_stage2, last_row_used


# ---------------------------------------------------------------------------
# Checkpoint discovery
# ---------------------------------------------------------------------------

def _find_best_checkpoint(checkpoint_dir: str) -> Optional[str]:
    """
    Locate the ``best-eval-step-*.ckpt`` file saved by GPTrainer.

    GPTrainer saves a new best whenever eval accuracy improves, deleting the
    previous best.  At the end of training exactly one such file should exist.
    If multiple files are present (e.g. training was interrupted), the one
    with the highest step number is returned.

    Parameters
    ----------
    checkpoint_dir : str
        Per-run checkpoint directory (``RunSetting.run_checkpoint_dir``).

    Returns
    -------
    str or None
        Absolute path to the best-eval checkpoint, or ``None`` if none found.
    """
    ckpt_dir = Path(checkpoint_dir)
    candidates = sorted(
        ckpt_dir.glob("best-eval-step-*.ckpt"),
        key=lambda p: int(p.stem.split("-")[-1]),  # sort by step number
    )
    if not candidates:
        return None
    return str(candidates[-1])


def _find_evaluation_checkpoints(
    checkpoint_dir: str,
    num_additional: int,
) -> List[str]:
    """
    Return the best-eval checkpoint plus up to ``num_additional`` nearby
    periodic checkpoints (``step-*.ckpt``), ordered: best first, then
    nearest periodic ones.

    Proximity is measured as ``|step - best_step|``.  Ties (equal distance
    on both sides) are broken by choosing the **later** step.

    Example
    -------
    Best checkpoint at step 278, ``num_additional=3``.
    Periodic steps available: 260, 280, 300, 320, …
    Distances: 260→18, 280→2, 300→22, 320→42, …
    Selected periodic steps (3 closest): 280, 260, 300.
    Returned list: [best-eval-step-278.ckpt,
                    step-280.ckpt, step-260.ckpt, step-300.ckpt]

    Parameters
    ----------
    checkpoint_dir : str
        Per-run checkpoint directory.
    num_additional : int
        Number of extra periodic checkpoints to include alongside the best
        checkpoint.  Pass 0 to evaluate the best checkpoint only.

    Returns
    -------
    list of str
        Absolute paths.  Empty list if no best-eval checkpoint exists.
    """
    ckpt_dir = Path(checkpoint_dir)

    # Locate best-eval checkpoint
    best_candidates = sorted(
        ckpt_dir.glob("best-eval-step-*.ckpt"),
        key=lambda p: int(p.stem.split("-")[-1]),
    )
    if not best_candidates:
        return []
    best_ckpt = best_candidates[-1]
    best_step = int(best_ckpt.stem.split("-")[-1])

    if num_additional == 0:
        return [str(best_ckpt)]

    # Collect all periodic step-*.ckpt files
    periodic: List[Tuple[int, Path]] = []
    for p in ckpt_dir.glob("step-*.ckpt"):
        try:
            step = int(p.stem.split("-")[-1])
            periodic.append((step, p))
        except ValueError:
            continue

    # Sort by (distance, -step): ties broken by choosing the later step
    periodic.sort(key=lambda x: (abs(x[0] - best_step), -x[0]))

    selected = [str(p) for _, p in periodic[:num_additional]]
    return [str(best_ckpt)] + selected


# ---------------------------------------------------------------------------
# Model loading (evaluation-only Trainer subclass)
# ---------------------------------------------------------------------------

class _EvalOnlyTrainer:
    """
    Thin wrapper that builds and loads a TabICL model from a checkpoint
    without launching any training.

    Reuses tabicl's ``Trainer``  (via ``GPTrainer``) for model construction
    and checkpoint loading, but overrides ``configure_prior`` so that no
    training data or DataLoader is needed.

    Parameters
    ----------
    checkpoint_path : str
        Path to the ``.ckpt`` file to load (usually the best-eval checkpoint).
    data_dir : str
        Required by ``_build_tabicl_config`` for GP-specific config fields;
        the manifest files inside it are **not** read unless ``train()`` is
        explicitly called (which it is not).
    max_features : int or None
        Must match the value used during training.
    device : str
        ``"cuda"`` or ``"cpu"``.
    tmp_dir : str
        Temporary directory for checkpoint/wandb artefacts created by the
        Trainer during initialisation.
    """

    def __init__(
        self,
        checkpoint_path: str,
        data_dir: str,
        max_features: Optional[int],
        device: str,
        tmp_dir: str,
    ):
        from train_gp import _build_tabicl_config
        from gp_trainer import GPTrainer

        # Minimal args namespace – mirrors what _single_run provides.
        args = argparse.Namespace(
            data_dir=data_dir,
            checkpoint_path=checkpoint_path,
            max_steps=1,               # non-zero so Trainer doesn't short-circuit
            batch_size=1,
            micro_batch_size=1,
            lr=1e-6,                   # irrelevant – no training
            weight_decay=0.0,
            save_perm_every=99999,
            save_temp_every=99999,
            n_eval=1,                  # placeholder – overridden by evaluate_tasks()
            eval_seed=0,
            train_manifest="train_manifest.csv",
            eval_manifest="eval_manifest.csv",
            wandb_log=False,
            wandb_project="_stage2_eval_tmp",
            wandb_name="_stage2_eval_tmp",
            wandb_mode="disabled",
            device=device,
            np_seed=42,
            torch_seed=42,
            max_features=max_features,
            no_cache_pickles=True,
            scheduler="constant",      # irrelevant – evaluation only, no training steps
            warmup_proportion=0.0,
        )

        Path(tmp_dir).mkdir(parents=True, exist_ok=True)
        config = _build_tabicl_config(args, ckpt_dir=tmp_dir, wandb_dir=tmp_dir)
        # Ensure max_features is propagated before evaluate_tasks() uses it
        config.gp_max_features = max_features

        # Subclass GPTrainer inline to skip configure_prior (no train data needed)
        class _NoPriorTrainer(GPTrainer):
            def configure_prior(self_inner):
                """Skip prior data setup – evaluation-only mode."""
                self_inner.dataloader = iter([])  # unused empty iterator

        self._trainer = _NoPriorTrainer(config)
        # Expose the loaded model and device for external use
        self.model  = self._trainer.raw_model
        self.device = device

    def evaluate_tasks(
        self,
        tasks: List[Tuple],
    ) -> Dict[str, float]:
        """
        Evaluate on a custom list of pre-built tasks.

        Parameters
        ----------
        tasks : list of (X_i, y_i, n_feat, seq_len, train_size)
            As returned by ``prepare_stage2_eval_batch``.

        Returns
        -------
        dict with keys ``"stage2_eval_acc"`` and ``"stage2_eval_ce"``
        """
        from gp_trainer import _eval_single_task

        self._trainer._eval_tasks = tasks
        raw = self._trainer._run_eval()
        return {
            "stage2_eval_acc": raw["eval_accuracy"],
            "stage2_eval_ce":  raw["eval_ce"],
        }


