# Main evaluation driver
# ---------------------------------------------------------------------------

def run_stage2_eval(
    manifest_path: str,
    n_eval: int,
    data_dir: str,
    device: Optional[str] = None,
    max_features: Optional[int] = None,
    eval_seed: int = 1,
    force_reeval: bool = False,
    eval_manifest_filename: str = "eval_manifest.csv",
    num_additional_checkpoints: int = 0,
) -> pd.DataFrame:
    """
    Evaluate the best checkpoint for every HPO setting on the Stage-2 held-out
    eval slice, then append three new columns to the HPO manifest CSV.

    This function is safe to call on **old HPO manifests** generated by
    earlier sweeps, as long as the checkpoint directories recorded in the
    manifest are still accessible.

    Stage-2 eval slice
    ------------------
    The eval manifest rows used are:

      row indices  n_eval  …  n_eval + floor((total − n_eval) / 2) − 1

    These rows were **not** seen during training (Stage-1 used rows 0..n_eval−1).

    New manifest columns
    --------------------
    ``stage2_eval_acc``
        Mean eval accuracy of the best checkpoint on the Stage-2 slice.
    ``stage2_eval_ce``
        Mean eval cross-entropy loss of the best checkpoint on the Stage-2 slice.
    ``stage2_last_row_used``
        0-based index of the last eval-manifest row consumed across both Stage-1
        and Stage-2 (same value for every run in a sweep; useful to determine
        the starting point for any future Stage-3 evaluation).

    Parameters
    ----------
    manifest_path : str
        Path to ``hpo_runs_manifest.csv``.
    n_eval : int
        ``gp_n_eval`` used during the HPO sweep (Stage-1 eval size).
    data_dir : str
        Root data directory containing the eval manifest and pickle files.
    device : str or None
        ``"cuda"`` or ``"cpu"``.  Defaults to ``"cuda"`` if a GPU is available.
    max_features : int or None
        Feature dimension used during training.  If None, auto-computed from
        the Stage-2 manifest slice (same logic as GPTrainer.configure_prior).
    eval_seed : int
        RNG seed for Stage-2 task construction.  Default 1 (differs from the
        Stage-1 seed of 0 to ensure independent sampling).
    force_reeval : bool
        If True, re-evaluate even if ``stage2_eval_acc`` already exists in the
        manifest.  If False (default), runs that already have Stage-2 results
        are skipped.
    eval_manifest_filename : str
        Filename of the eval manifest CSV inside ``data_dir``.
    num_additional_checkpoints : int
        Number of periodic ``step-*.ckpt`` checkpoints nearest to the best
        checkpoint to also evaluate.  The reported ``stage2_eval_acc`` and
        ``stage2_eval_ce`` are the **median** over all
        ``num_additional_checkpoints + 1`` checkpoints.  Default 0 (best
        checkpoint only, no median – matches the original behaviour).

    Returns
    -------
    pd.DataFrame
        The updated manifest with Stage-2 columns added (also saved to disk).
    """
    if device is None:
        device = "cuda" if torch.cuda.is_available() else "cpu"

    manifest_path = Path(manifest_path).expanduser().resolve()
    if not manifest_path.is_file():
        raise FileNotFoundError(f"Manifest not found: {manifest_path}")

    manifest = pd.read_csv(manifest_path)

    # ---- Check if Stage-2 already done for all runs -------------------------
    already_done_col = "stage2_eval_acc"
    if already_done_col in manifest.columns and not force_reeval:
        n_done = manifest[already_done_col].notna().sum()
        print(
            f"Stage-2 evaluation: {n_done}/{len(manifest)} runs already have "
            f"results.  Use force_reeval=True to re-run all."
        )

    # ---- Prepare Stage-2 eval tasks (shared across all runs) ----------------
    print(f"\nPreparing Stage-2 eval batch ...")
    print(f"  data_dir          : {data_dir}")
    print(f"  eval_manifest     : {eval_manifest_filename}")
    print(f"  n_eval (stage-1)  : {n_eval}")

    stage2_tasks, n_stage2, last_row_used = prepare_stage2_eval_batch(
        data_dir=data_dir,
        n_eval_stage1=n_eval,
        eval_manifest_filename=eval_manifest_filename,
        max_features=max_features,
        seed=eval_seed,
    )

    print(f"  stage-2 tasks     : {n_stage2}  (rows {n_eval}..{last_row_used})")
    print(f"  stage2_last_row_used: {last_row_used}")

    # ---- Initialise output columns if not present ---------------------------
    for col in ["stage2_eval_acc", "stage2_eval_ce", "stage2_last_row_used"]:
        if col not in manifest.columns:
            manifest[col] = pd.NA

    # ---- Evaluate each run --------------------------------------------------
    # Create a single shared tmp directory for Trainer artefacts
    tmp_dir = str(manifest_path.parent / "_stage2_eval_tmp")

    for idx, row in manifest.iterrows():
        run_name = row["run_name"]

        # Skip if already done and not forcing re-evaluation
        if (
            not force_reeval
            and "stage2_eval_acc" in manifest.columns
            and pd.notna(manifest.at[idx, "stage2_eval_acc"])
        ):
            print(f"  [SKIP] {run_name}  (already evaluated)")
            continue

        ckpt_dir = str(row["checkpoint_dir"])
        ckpt_paths = _find_evaluation_checkpoints(ckpt_dir, num_additional_checkpoints)

        if not ckpt_paths:
            print(f"  [WARN] {run_name}  – no best-eval checkpoint found in {ckpt_dir}")
            continue

        print(f"  [EVAL] {run_name}  ({len(ckpt_paths)} checkpoint(s))")
        for cp in ckpt_paths:
            print(f"         {Path(cp).name}")

        accs: List[float] = []
        ces:  List[float] = []

        for ckpt_path in ckpt_paths:
            try:
                evaluator = _EvalOnlyTrainer(
                    checkpoint_path=ckpt_path,
                    data_dir=data_dir,
                    max_features=max_features,
                    device=device,
                    tmp_dir=tmp_dir,
                )
                res = evaluator.evaluate_tasks(stage2_tasks)
                accs.append(res["stage2_eval_acc"])
                ces.append(res["stage2_eval_ce"])
                print(
                    f"         {Path(ckpt_path).name}: "
                    f"acc={res['stage2_eval_acc']:.4f}  "
                    f"ce={res['stage2_eval_ce']:.4f}"
                )
            except Exception as exc:
                print(f"  [ERROR] {run_name}  ckpt={Path(ckpt_path).name}  – {exc}")
            finally:
                # Free GPU memory after each checkpoint
                try:
                    del evaluator
                except NameError:
                    pass
                if torch.cuda.is_available():
                    torch.cuda.empty_cache()

        if not accs:
            print(f"  [WARN] {run_name}  – all checkpoints failed; skipping")
            continue

        med_acc = float(np.median(accs))
        med_ce  = float(np.median(ces))

        manifest.at[idx, "stage2_eval_acc"]      = med_acc
        manifest.at[idx, "stage2_eval_ce"]       = med_ce
        manifest.at[idx, "stage2_last_row_used"] = last_row_used

        print(
            f"         → median over {len(accs)} ckpt(s): "
            f"acc={med_acc:.4f}  ce={med_ce:.4f}"
        )

    # ---- Save updated manifest ----------------------------------------------
    manifest.to_csv(manifest_path, index=False)
    print(f"\nUpdated manifest saved: {manifest_path}")

    # Also overwrite the companion manifest in the checkpoint dir (if it exists)
    ckpt_manifest = manifest_path.parent.parent / manifest_path.parent.name.split("/")[-1]
    # Locate paired checkpoint root manifest via the first row's checkpoint_dir
    if not manifest.empty and "checkpoint_dir" in manifest.columns:
        first_ckpt_dir = Path(str(manifest.iloc[0]["checkpoint_dir"]))
        companion = first_ckpt_dir.parent / "hpo_runs_manifest.csv"
        if companion.is_file():
            manifest.to_csv(companion, index=False)
            print(f"Companion manifest updated: {companion}")

    return manifest


# ---------------------------------------------------------------------------
# CLI entry-point
# ---------------------------------------------------------------------------

def _build_cli_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description=(
            "Post-hoc Stage-2 evaluation of best HPO checkpoints on "
            "held-out eval-manifest rows."
        ),
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    p.add_argument(
        "--manifest_path", required=True,
        help="Path to hpo_runs_manifest.csv.",
    )
    p.add_argument(
        "--n_eval", type=int, required=True,
        help="gp_n_eval used during the HPO sweep (Stage-1 eval size).",
    )
    p.add_argument(
        "--data_dir", required=True,
        help="Root data directory containing eval_manifest.csv and pickles.",
    )
    p.add_argument(
        "--device", default=None,
        help="'cuda' or 'cpu'.  Default: cuda if available.",
    )
    p.add_argument(
        "--max_features", type=int, default=None,
        help="Feature dimension used during training.  Default: auto from eval manifest.",
    )
    p.add_argument(
        "--eval_seed", type=int, default=1,
        help="RNG seed for Stage-2 task construction.",
    )
    p.add_argument(
        "--eval_manifest", default="eval_manifest.csv",
        help="Filename of the eval manifest CSV inside data_dir.",
    )
    p.add_argument(
        "--force_reeval", action="store_true", default=False,
        help="Re-evaluate even if stage2_eval_acc already present in manifest.",
    )
    p.add_argument(
        "--num_additional_checkpoints", type=int, default=0,
        help=(
            "Number of periodic step-*.ckpt checkpoints nearest to the best "
            "checkpoint to also evaluate.  Reported metrics are the median "
            "over all num_additional_checkpoints+1 checkpoints.  "
            "Default 0 (best checkpoint only)."
        ),
    )
    return p


def main() -> None:
    args = _build_cli_parser().parse_args()
    run_stage2_eval(
        manifest_path=args.manifest_path,
        n_eval=args.n_eval,
        data_dir=args.data_dir,
        device=args.device,
        max_features=args.max_features,
        eval_seed=args.eval_seed,
        force_reeval=args.force_reeval,
        eval_manifest_filename=args.eval_manifest,
        num_additional_checkpoints=args.num_additional_checkpoints,
    )


if __name__ == "__main__":
    main()
